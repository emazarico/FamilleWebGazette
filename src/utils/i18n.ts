export const TRANSLATIONS: Record<UiLanguage, Record<TranslationKey, string>> = {
  fr: FR_TRANSLATIONS,
  en: EN_TRANSLATIONS,
};

export function t(
  lang: UiLanguage,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.fr;
  let value = dict[key] ?? FR_TRANSLATIONS[key] ?? key;
  if (params) {
    for (const [paramKey, paramVal] of Object.entries(params)) {
      value = value.replaceAll(`{${paramKey}}`, String(paramVal));
    }
  }
  return value;
}

export function formatMemoryDate(isoDate: string, lang: UiLanguage): string {
  if (!isoDate) return '';
  const parts = isoDate.slice(0, 10).split('-').map(Number);
  if (parts.length !== 3 || parts.some((n) => Number.isNaN(n))) return isoDate;
  const [y, m, d] = parts;
  const dateObj = new Date(Date.UTC(y, m - 1, d));
  try {
    return new Intl.DateTimeFormat(lang === 'fr' ? 'fr-FR' : 'en-US', {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
      timeZone: 'UTC',
    }).format(dateObj);
  } catch {
    return isoDate;
  }
}

export function formatRelativeTime(
  isoDateTime: string,
  lang: UiLanguage,
  nowMs: number = Date.now(),
): string {
  const ts = Date.parse(isoDateTime);
  if (Number.isNaN(ts)) return '';
  const diffMinutes = Math.max(0, Math.floor((nowMs - ts) / 60_000));
  if (diffMinutes < 5) return t(lang, 'justNow');
  const diffHours = Math.floor(diffMinutes / 60);
  if (diffHours < 24) return t(lang, 'hoursAgo', { n: Math.max(1, diffHours) });
  const diffDays = Math.floor(diffHours / 24);
  if (diffDays === 1) return t(lang, 'yesterday');
  if (diffDays < 30) return t(lang, 'daysAgo', { n: diffDays });
  return formatMemoryDate(isoDateTime.slice(0, 10), lang);
}
